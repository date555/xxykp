"""Freeze audited original bodies and projectile references, including skin variants."""
from pathlib import Path
import json,shutil,hashlib
from audit_content import ROOT,WORK,tower,avatars,language,check_asset,source_file
roster=json.loads((ROOT/'tools/asset-roster.json').read_text(encoding='utf8'))
out=ROOT/'assets/spine';out.mkdir(parents=True,exist_ok=True)
records=[];assets={};mapping={};variants={};bosses={}
def record(src,dest):records.append(dict(file=dest.relative_to(ROOT).as_posix(),source=str(src.relative_to(WORK)),sha256=hashlib.sha256(dest.read_bytes()).hexdigest()))
def copy(src,dest):
 if not src:raise ValueError('Source file missing for '+str(dest))
 dest.parent.mkdir(parents=True,exist_ok=True);shutil.copyfile(src,dest);record(src,dest)
def asset(bundle,name):
 key=bundle+'/'+name
 if key in assets:return key
 meta,fields,src,textures=check_asset(bundle,name)
 target=out/bundle;dest=target/(name+'.atlas');dest.parent.mkdir(parents=True,exist_ok=True)
 dest.write_text(fields['_atlasText'],encoding='utf8');record(src,dest)
 data=fields.get('_skeletonJson');fmt='json' if data else 'bin'
 if data:
  dest=target/(name+'.json');dest.write_text(data if isinstance(data,str) else json.dumps(data),encoding='utf8');record(src,dest)
 else:copy(source_file(bundle+'/native/'+name+'.bin'),target/(name+'.bin'))
 for tex in textures:copy(source_file(str(Path(bundle)/'native'/Path(name).parent/tex)),target/Path(name).parent/tex)
 assets[key]=dict(bundle=bundle,name=name,format=fmt,width=meta['width'],height=meta['height'],animations=meta['animations'],textures=textures,sourceMeta=str(src.relative_to(WORK)))
 return key
for hero,looks in roster['appearances'].items():
 for look in looks:
  row=avatars[str(look['avatarId'])];body=look['body'];hero_meta=tower['SkeletonConf'][body]
  m=dict(avatarId=row['id'],heroId=hero,body=asset(row['path'],body),skin=row['skin'],height=hero_meta['height'])
  for mode in ['attack','skill']:
   bullet=tower['BulletConf'][str(row[mode+'Bullets'][0])];fx=tower['EffectConf'][str(bullet['effect'])]
   hit_id=row[mode+'Damage'] or bullet.get('damageEffect',0);hit=tower['EffectConf'][str(hit_id)] if hit_id else None
   anim=next(a for a in hero_meta['animations'] if a['name']==mode)
   m[mode]=dict(asset=asset(fx['bundle'],fx['uri']),type=bullet['type'],params=bullet['params'],bullet=bullet,effect=fx,hitEffectId=hit_id,hitAsset=asset(hit['bundle'],hit['uri']) if hit else None,hitEffect=hit,castTime=anim['hits'][0] if anim['hits'] else .3,castDuration=anim['duration'])
   m[mode]['effectDuration']=assets[m[mode]['asset']]['animations'][0]['duration']
   m[mode]['effectHitTime']=next(iter(assets[m[mode]['asset']]['animations'][0]['hits']),0)
   m[mode]['hitDuration']=assets[m[mode]['hitAsset']]['animations'][0]['duration'] if m[mode]['hitAsset'] else 0
  variants[look['id']]=m
  for kind,field in [('head','sourceHead'),('body','sourcePortrait')]:copy(source_file('icons/native/'+look[field]+'.png'),ROOT/f'assets/appearances/{look["id"]}-{kind}.png')
 mapping[hero]=variants[looks[0]['id']]
for boss in roster['bosses']:
 row=avatars[str(boss['avatarId'])];body=row.get('asset') or row['path'];key=asset(row['path'],body)
 bosses[boss['id']]=dict(body=key,skin=row['skin'],height=assets[key]['height'],animations=[a['name'] for a in assets[key]['animations']])
toys={}
for toy,icon in [('ice','bingzhenpijiuping'),('arrow','yizhichuanyunjian'),('heal','zuchuandabing')]:
 row=next(v for v in language['WeaponConf'].values() if v.get('icon')=='weapons/'+icon)
 bullet=tower['BulletConf'][str(row['bullets'][0])];fx=tower['EffectConf'][str(bullet['effect'])]
 key=asset(fx['bundle'],fx['uri']);anim=assets[key]['animations'][0]
 toys[toy]=dict(weaponId=row['id'],bullet=bullet,effect=fx,asset=key,duration=anim['duration'],hitTime=anim['hits'][0],speed=1.7)
statuses={}
for name,effect_id in [('frozen',10001),('recovery',10003)]:
 fx=tower['EffectConf'][str(effect_id)];key=asset(fx['bundle'],fx['uri']);statuses[name]=dict(asset=key,effect=fx,duration=assets[key]['animations'][0]['duration'])
doc=dict(configVersion='58b91ed6c8',assetVersion='audited-local-versions',sourceTables=['HeroConf','SkinConf','AvatarConf','WeaponConf','BulletConf','EffectConf','SkeletonConf'],heroes=mapping,appearances=variants,bosses=bosses,toys=toys,statuses=statuses,assets=assets,files=records)
(out/'manifest.json').write_text(json.dumps(doc,ensure_ascii=False,indent=2),encoding='utf8')
text='// Generated by tools/prepare-spine.py; original references only.\n'
for name,value in [('ANIMATIONS',mapping),('APPEARANCE_ANIMATIONS',variants),('BOSS_ANIMATIONS',bosses),('TOY_ANIMATIONS',toys),('STATUS_ANIMATIONS',statuses)]:text+='export const '+name+'='+json.dumps(value,ensure_ascii=False,separators=(',',':'))+';\n'
text+='export function animationFor(hero){return APPEARANCE_ANIMATIONS[String(hero.avatarId)]||ANIMATIONS[hero.id];}\n'
(ROOT/'src/animation-data.js').write_text(text,encoding='utf8')
print('Spine ready:',len(mapping),'heroes,',len(variants),'appearances,',len(bosses),'bosses,',len(assets),'skeletons')

